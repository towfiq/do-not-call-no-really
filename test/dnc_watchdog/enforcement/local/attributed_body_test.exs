  test "extract_text/1 decodes a real macOS attributedBody blob" do
    assert AttributedBody.extract_text(@real_blob_testing) == "Testing with imsg installed"
  end

  test "extract_text/1 decodes synthetic blobs" do
    blob = SqliteFixtures.make_attributed_body("CA Roofing promo from Annie")
    assert AttributedBody.extract_text(blob) == "CA Roofing promo from Annie"
  end

  test "extract_text/1 handles UTF-8 bytes that look like end markers" do
    text = "before\u2184after"
    blob = SqliteFixtures.make_attributed_body(text)
    assert AttributedBody.extract_text(blob) == text
  end

  test "extract_text/1 prefers the longest decodable marker segment" do
    good = SqliteFixtures.make_attributed_body("Annie from CA Roofing")
    <<prefix::binary-size(20), rest::binary>> = good
    blob = prefix <> <<0x01, 0x2B, 0x03, 0xFF, 0xFE, 0xFD>> <> rest

    assert AttributedBody.extract_text(blob) == "Annie from CA Roofing"
  end

  test "extract_text/1 returns nil for unparseable blobs" do
    assert AttributedBody.extract_text("not a blob") == nil
    assert AttributedBody.extract_text(<<0x01, 0x2B, 0x04, 0xFF, 0xFE, 0x80, 0x81>>) == nil
  end
end
